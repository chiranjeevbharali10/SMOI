"""Writes docs/benchmarks.md from results files. Every number in it comes from those files."""

import json
from datetime import datetime, timezone
from pathlib import Path

from .environment import REPO

BENCHMARKS = REPO / "docs" / "benchmarks.md"
MODE_LABELS = {"keyword": "keyword", "vector": "vector", "hybrid": "hybrid (RRF)", "hybrid_rerank": "hybrid + rerank"}


def pct(value) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def num(value, digits=3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def ms(value) -> str:
    return "n/a" if value is None else f"{value:,.0f} ms"


def rel(path: Path) -> str:
    return path.resolve().relative_to(REPO).as_posix()


def write(results_path: Path, sweep_path: Path | None, locked_log: list[dict], question_status: dict) -> Path:
    r = json.loads(results_path.read_text(encoding="utf-8"))
    sweep = json.loads(sweep_path.read_text(encoding="utf-8")) if sweep_path else None
    run, env = r["run"], r["environment"]
    out: list[str] = []
    w = out.append

    w("# SMOI benchmarks")
    w("")
    w(f"Generated by `eval/run_eval.py report` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC from "
      f"`{rel(results_path)}`" + (f" and `{rel(sweep_path)}`" if sweep_path else "") + ". Do not edit by hand; "
      "run `make eval` (or `python eval/run_eval.py all`) to regenerate it.")
    w("")

    approved, total = question_status["approve"], question_status["total"]
    if run["question_set"] == "draft" or approved == 0:
        w(f"> **DRAFT: these results are not final.** The question set has not been reviewed yet "
          f"({approved} of {total} questions approved). This run used all {run['questions']} questions that "
          "weren't rejected. Numbers will change once the reviewed, split question set is used.")
        w("")
    elif run["question_set"] == "tuning":
        w(f"> These are **tuning-set** results ({run['questions']} of {approved} approved questions). Settings "
          "were chosen on this set, so they are optimistic. The headline numbers come from the locked test set.")
        w("")
    elif run["question_set"] == "test":
        w(f"> **Headline results: locked test set** ({run['questions']} of {approved} approved questions). "
          "No settings were tuned on these questions.")
        w("")
    w(_locked_note(locked_log))
    w("")

    # ---------- setup ----------
    p = run["providers"]
    w("## Setup")
    w("")
    w(f"- **Commit:** `{env['git']['commit'][:12]}`" + (" (with uncommitted changes)" if env["git"]["dirty"] else ""))
    w(f"- **Question set:** `eval/data/questions_v1.csv`, set `{run['question_set']}`: {run['questions']} questions "
      f"({run['answerable']} answerable, {run['questions'] - run['answerable']} not answerable). "
      f"{approved} of {total} approved by the owner.")
    c = r["corpus"]
    w(f"- **Corpus:** {c['documents']} documents ({', '.join(f'{n} {k.upper()}' for k, n in sorted(c['formats'].items()))}), "
      f"{c['bytes'] / 1024:,.0f} KiB, {c['chunks']} chunks, in groups {', '.join(c['groups'])} "
      "(`eval/corpus/SOURCES.md`).")
    w(f"- **Chunking:** {p['chunking']['maxTokens']} tokens, {p['chunking']['overlapTokens']} overlap (estimated as characters / 4).")
    w(f"- **Embedding model:** `{p['embedding']['model']}`.")
    w(f"- **Answer model:** `{p['llm']['provider']}` / `{p['llm']['model']}`; answers use mode `{run['answer_mode']}`.")
    w(f"- **Reranker:** {p['reranker']['model'] if p['reranker']['enabled'] else 'disabled'}"
      f"{', ' + str(run['rerank_candidates']) + ' candidates' if p['reranker']['enabled'] else ''}.")
    if r.get("judge"):
        j = r["judge"]
        w(f"- **Faithfulness judge:** `{j['spec']}`. {j['note']}")
    hw = env["hardware"]
    docker = hw.get("docker") or {}
    w(f"- **Hardware:** {hw.get('cpu')} ({hw.get('logical_cpus')} logical CPUs), {hw.get('ram_gib', '?')} GiB RAM, "
      f"{hw.get('os')}. Docker: {docker.get('cpus')} CPUs, {docker.get('memory_gib')} GiB "
      f"({docker.get('os')}). Models run on the CPU; no GPU.")
    w(f"- **Indexing time:** {c['index_seconds']:.0f} s for the whole corpus.")
    w("")

    # ---------- retrieval ----------
    retr = r["retrieval"]["summary"]
    w("## Retrieval quality (NFR-09.01, NFR-09.02)")
    w("")
    w(f"Over the {run['answerable']} answerable questions; top 10 results per query. A chunk counts as relevant "
      "if it contains a labelled evidence quote.")
    w("")
    w("| Mode | Recall@5 | Recall@10 | MRR@10 | nDCG@10 |")
    w("| --- | --- | --- | --- | --- |")
    for mode, s in retr.items():
        o = s["overall"]
        flag = " (reranker not applied to every query: invalid)" if mode == "hybrid_rerank" and s["rerank_applied"] != s["latency_ms"]["queries"] else ""
        w(f"| {MODE_LABELS[mode]}{flag} | {num(o.get('recall@5'))} | {num(o.get('recall@10'))} | {num(o.get('mrr@10'))} | {num(o.get('ndcg@10'))} |")
    w("")
    w("**Per group** (Recall@5 / MRR@10):")
    w("")
    groups = sorted({g for s in retr.values() for g in s["by_group"]})
    w("| Mode | " + " | ".join(groups) + " |")
    w("| --- |" + " --- |" * len(groups))
    for mode, s in retr.items():
        cells = [f"{num(s['by_group'][g].get('recall@5'))} / {num(s['by_group'][g].get('mrr@10'))}" for g in groups]
        w(f"| {MODE_LABELS[mode]} | " + " | ".join(cells) + " |")
    w("")
    w("**Per question type** (Recall@5 / MRR@10):")
    w("")
    types = sorted({t for s in retr.values() for t in s["by_type"]})
    w("| Mode | " + " | ".join(types) + " |")
    w("| --- |" + " --- |" * len(types))
    for mode, s in retr.items():
        cells = [f"{num(s['by_type'][t].get('recall@5'))} / {num(s['by_type'][t].get('mrr@10'))}" for t in types]
        w(f"| {MODE_LABELS[mode]} | " + " | ".join(cells) + " |")
    w("")

    # ---------- answers ----------
    if r.get("answers"):
        a = r["answers"]["summary"]
        w("## Answer quality (NFR-09.03 to NFR-09.05)")
        w("")
        w(f"{a['questions']} questions sent to `/api/query` (mode `{run['answer_mode']}`). Outcomes: "
          + ", ".join(f"{k} {v}" for k, v in sorted(a["outcomes"].items())) + ".")
        w("")
        w("| Metric | Value | How it is measured |")
        w("| --- | --- | --- |")
        w(f"| Correct \"don't know\" on unanswerable questions | {pct(a['correct_dont_know_rate'])} | deterministic: outcome `dont_know` |")
        w(f"| Unanswerable questions answered anyway | {pct(a['answered_unanswerable_rate'])} | deterministic |")
        w(f"| Answerable questions wrongly refused (\"don't know\") | {pct(a['false_dont_know_rate'])} | deterministic |")
        w(f"| Answerable questions answered | {pct(a['answered_rate_answerable'])} | deterministic |")
        w(f"| Answers rejected for invalid citations | {pct(a['citation_rejected_rate'])} | deterministic: backend check (FR-06.12) |")
        w(f"| Accepted citations naming a retrieved chunk (NFR-09.04) | {'100%' if a['accepted_citations_in_corpus'] else 'FAILED'} | deterministic: enforced by the backend, re-checked here |")
        w(f"| Cited chunks that contain labelled evidence | {pct(a['cited_chunk_evidence_precision'])} | deterministic |")
        w(f"| Answers citing at least one evidence chunk | {pct(a['answers_citing_evidence_rate'])} | deterministic |")
        if r.get("judge"):
            js = r["judge"]["summary"]
            agreement = r["judge"].get("agreement")
            agree_text = (f"agreement with owner's labels: {pct(agreement['percent'])}, Cohen's kappa {num(agreement['kappa'], 2)} "
                          f"on {agreement['sentences']} sentences" if agreement else "owner's hand labels not available yet, so agreement is unknown")
            w(f"| Faithfulness (share of answer sentences supported by the passages they cite) | **estimate:** {num(js['mean_faithfulness'], 2)} | LLM judge; {agree_text} |")
            w(f"| Answers with every sentence supported | **estimate:** {pct(js['fully_faithful_rate'])} | LLM judge |")
        w("")
        w("**Per group:**")
        w("")
        w("| Group | Correct \"don't know\" | Wrongly refused | Citing evidence" + (" | Faithfulness (estimate)" if r.get("judge") else "") + " |")
        w("| --- | --- | --- | ---" + (" | ---" if r.get("judge") else "") + " |")
        for g, s in a["by_group"].items():
            faith = f" | {num(r['judge']['summary']['by_group'].get(g), 2)}" if r.get("judge") else ""
            w(f"| {g} | {pct(s['correct_dont_know_rate'])} | {pct(s['false_dont_know_rate'])} | {pct(s['answers_citing_evidence_rate'])}{faith} |")
        w("")

    # ---------- latency ----------
    w("## Latency (NFR-09.08, NFR-01.05)")
    w("")
    w("Retrieval only, per mode (wall time measured by the harness; server time from the response):")
    w("")
    w("| Mode | p50 | p95 | Server p50 | Server p95 | Queries |")
    w("| --- | --- | --- | --- | --- | --- |")
    for mode, s in retr.items():
        lat = s["latency_ms"]
        w(f"| {MODE_LABELS[mode]} | {ms(lat['wall_p50'])} | {ms(lat['wall_p95'])} | {ms(lat['server_p50'])} | {ms(lat['server_p95'])} | {lat['queries']} |")
    w("")
    if r.get("answers"):
        stage_names = {"retrievalMs": "retrieval", "rerankMs": "rerank", "firstTokenMs": "time to first token",
                       "generationMs": "generation", "totalMs": "total"}
        w(f"Answers (`/api/query`, mode `{run['answer_mode']}`), per stage:")
        w("")
        w("| Stage | p50 | p95 |")
        w("| --- | --- | --- |")
        for key, value in r["answers"]["summary"]["latency_ms"].items():
            w(f"| {stage_names[key]} | {ms(value['p50'])} | {ms(value['p95'])} |")
        w("")

    # ---------- chunk sweep ----------
    if sweep:
        w("## Chunk size experiment")
        w("")
        w(f"Retrieval only, on the `{sweep['question_set']}` set ({sweep['answerable']} answerable questions), "
          f"commit `{sweep['commit'][:12]}`. Each size re-indexes the corpus for a fresh user.")
        w("")
        modes = list(sweep["configs"][0]["summary"].keys())
        w("| Chunk tokens / overlap | Chunks | " + " | ".join(f"{MODE_LABELS[m]} R@5 / MRR" for m in modes) + " |")
        w("| --- | --- |" + " --- |" * len(modes))
        for cfg in sweep["configs"]:
            cells = [f"{num(cfg['summary'][m]['overall'].get('recall@5'))} / {num(cfg['summary'][m]['overall'].get('mrr@10'))}" for m in modes]
            w(f"| {cfg['chunk_tokens']} / {cfg['chunk_overlap']} | {cfg['chunks']} | " + " | ".join(cells) + " |")
        w("")

    # ---------- worst ----------
    w("## The 10 worst questions")
    w("")
    w(f"Lowest per-question score in mode `{run['answer_mode']}` (mean of recall@5, MRR@10, answered, cited the "
      "evidence; for unanswerable questions, whether the reply was \"don't know\"). Likely causes are discussed in "
      "`eval/analysis.md`, which is written by hand.")
    w("")
    w("| Question | Group | Type | Score | What went wrong |")
    w("| --- | --- | --- | --- | --- |")
    for q in r["worst"]:
        w(f"| {q['id']}: {q['question']} | {q['group']} | {q['type']} | {q['score']:.2f} | {'; '.join(q['problems']) or '-'} |")
    w("")

    # ---------- definitions ----------
    w("## Definitions")
    w("")
    w("- **Recall@k:** share of a question's evidence items found in the top k chunks, averaged over questions.")
    w("- **MRR@10:** 1 / rank of the first chunk containing any evidence (0 if none in the top 10), averaged.")
    w("- **nDCG@10:** rewards finding each evidence item, more so at higher ranks; chunks repeating evidence "
      "already found earn nothing. 1.0 means one chunk per evidence item, at the top.")
    w("- **Percentiles** use the nearest-rank method.")
    w("- **Faithfulness** is judged by an LLM and is an estimate; the judge model and its agreement with the "
      "owner's hand labels are stated next to the number. All other answer metrics are computed by code.")
    w("- Raw per-question results, including every retrieved chunk and answer, are in the results files named at the top.")
    w("")
    BENCHMARKS.write_text("\n".join(out), encoding="utf-8")
    return BENCHMARKS


def _locked_note(locked_log: list[dict]) -> str:
    if not locked_log:
        return "The locked test set has not been run yet."
    fingerprints = []
    for entry in locked_log:
        if entry["fingerprint"] not in fingerprints:
            fingerprints.append(entry["fingerprint"])
    lines = [f"The locked test set has been run {len(locked_log)} time(s) "
             f"(`eval/results/locked_runs.jsonl`):"]
    lines += [f"- {e['timestamp']} commit `{e['commit'][:12]}`, settings `{e['fingerprint'][:12]}`, results `{e['results']}`"
              for e in locked_log]
    if len(fingerprints) > 1:
        lines.append("")
        lines.append("> **Settings were changed after locked test results had been seen.** The later test results "
                     "are therefore not a clean held-out measurement.")
    return "\n".join(lines)

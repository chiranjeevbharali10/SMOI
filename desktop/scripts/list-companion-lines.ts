/**
 * Writes docs/companion-lines.md: for each companion other than SMOI, every event that has no line
 * in its own voice yet, with the fallback it shows today (shared/voice.ts).
 *
 *   npx tsx scripts/list-companion-lines.ts
 *
 * To give a companion its own line, add it to that companion's manifest under "event_lines", keyed
 * by the event, with the facts as {placeholders}; for example
 *   "event_lines": { "claude_done": "Claude Code finished in {duration}. Took its time." }
 * A line that leaves out one of the event's placeholders is ignored, so facts are never dropped.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readRoster } from '../src/main/companionRoster';
import { effectOf, FINDING, LISTENING, type BubbleLine, type PanelEvent } from '../src/shared/panelActions';
import { PRESETS, react, type CompanionEvent } from '../src/shared/personality';
import { eventKey, facts, fitsVoice, panelLine, reactAs } from '../src/shared/voice';

const DESKTOP = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const roster = readRoster(join(DESKTOP, 'assets', 'companions'));
const P = PRESETS.classic.values;

/** One example of each event, with made-up facts. */
const EVENTS: CompanionEvent[] = [
  { type: 'reminder', title: 'Call mum', missed: false },
  { type: 'reminder', title: 'Call mum', missed: true },
  { type: 'overdue', count: 3 },
  { type: 'indexed', count: 2 },
  { type: 'task_saved', title: 'Buy oat milk' },
  { type: 'reminder_saved', title: 'Stretch', when: 'Tue 4 Nov, 18:00' },
  { type: 'claude_done', minutes: 12 },
  { type: 'claude_waiting' },
  { type: 'important_email', count: 1 },
  { type: 'google_reconnect' },
  { type: 'draft_reminder_cancelled', message: 'Your draft “Report” was sent or deleted in Gmail, so I cancelled its reminder.' },
  { type: 'google_done', text: 'Added to your Google Calendar.' },
];

const PANEL: { key: string; line: BubbleLine | null; note?: string }[] = [
  ...(['hello', 'closed', 'talk', 'calendar', 'inbox', 'dashboard'] as PanelEvent[]).map((e) => ({
    key: e,
    line: effectOf(e, undefined, { openTasks: 3, busyToday: true, newEmails: 2 })?.bubble ?? null,
  })),
  { key: 'listening', line: { tone: 'nudge', text: LISTENING.line } },
  { key: 'finding', line: FINDING },
];

const esc = (s: string) => s.replace(/\|/g, '\\|');
const out: string[] = [
  '# Companion lines to write',
  '',
  'Generated by `npx tsx desktop/scripts/list-companion-lines.ts`. Do not edit by hand: add lines to the',
  'companion\'s `manifest.json` under `event_lines` and run the script again.',
  '',
  '- **Event key** is what to put in `event_lines`. App events can use the listed placeholders (all of',
  '  them must appear, so no fact is dropped). Panel lines start with `panel_` and take no placeholders.',
  "- The panel's task-count line (\"Hey, you've got 3 things to do!\") always uses the shared line, because it carries the count.",
  '- **Shown today** is the fallback at the default personality ("Classic"); other personality styles',
  '  word the shared lines differently. A shared line that names SMOI or refers to being a frog is never',
  '  shown for another companion: the plain version is used instead, or no bubble if that fails too.',
  '',
];

for (const c of roster.companions.filter((x) => x.id !== 'smoi')) {
  out.push(`## ${c.name} (${c.creature})`, '', `Voice: ${c.personality}`, '');
  out.push('| Event key | Placeholders | Shared line (Classic) | Shown today for this companion |', '| --- | --- | --- | --- |');
  for (const e of EVENTS) {
    const key = eventKey(e);
    if (c.eventLines[key]) continue;
    const shared = react(e, P).line?.text ?? '(no bubble)';
    const shown = reactAs(c, e, P).line?.text ?? '(no bubble)';
    const ph = Object.keys(facts(e)).map((k) => `{${k}}`).join(' ') || 'none';
    const note = shared === shown ? shown : `${shown} *(shared line blocked: ${fitsVoice(c, shared) ? 'style' : 'names SMOI or frog'})*`;
    out.push(`| \`${key}\` | ${ph} | ${esc(shared)} | ${esc(note)} |`);
  }
  for (const p of PANEL) {
    const key = `panel_${p.key}`;
    if (c.eventLines[key]) continue;
    const shared = p.line?.text ?? '(no bubble)';
    const shown = p.line ? panelLine(c, p.key, p.line, () => 0)?.text ?? '(no bubble: shared line names SMOI or frog)' : '(no bubble)';
    const note = p.key === 'hello' ? `${shown} *(one of its manifest lines, at random)*` : shown;
    out.push(`| \`${key}\` | none | ${esc(shared)} | ${esc(note)} |`);
  }
  out.push('');
}

const file = join(DESKTOP, '..', 'docs', 'companion-lines.md');
writeFileSync(file, out.join('\n'));
console.log(`wrote ${file}`);

/**
 * Speech bubbles in the active companion's voice.
 *
 * - A companion can have its own line for an event (manifest "event_lines", a template with the
 *   event's facts as {placeholders}). A template that leaves out a fact (a title, a count, a time)
 *   is ignored, so no line ever drops a fact.
 * - Otherwise the shared line (shared/personality.ts, written in SMOI's voice) is used, with one
 *   guard: while another companion is active, a line that names SMOI or refers to being a frog
 *   counts as missing. The plain version of the same line is used instead if it passes; if not,
 *   there is no bubble (the frog's reaction still happens).
 * - Panel lines work the same way, except "hello", which other companions take from their own
 *   manifest "lines".
 *
 * docs/companion-lines.md (generated by scripts/list-companion-lines.ts) lists every event without
 * a line of its own, per companion, with the fallback it uses today.
 *
 * Pure; tested in test/voice.test.ts.
 */
import type { Companion } from './companions';
import type { BubbleLine } from './panelActions';
import { react, type CompanionEvent, type Personality, type Reaction } from './personality';

export type Voice = Pick<Companion, 'id' | 'name' | 'lines' | 'eventLines'>;

/** Words that only make sense coming from SMOI the frog. */
const SMOI_ONLY = /\bSMOI\b|\bfrogs?\b|\bribbit\b|\blily[ -]?pads?\b|\bponds?\b|\btoads?\b|\btadpoles?\b/i;

export function fitsVoice(c: Pick<Companion, 'id'>, text: string): boolean {
  return c.id === 'smoi' || !SMOI_ONLY.test(text);
}

/** The key an event's own line is stored under in a manifest's event_lines. */
export function eventKey(e: CompanionEvent): string {
  return e.type === 'reminder' && e.missed ? 'reminder_missed' : e.type;
}

/** The facts each event's line must carry, by placeholder name. */
export function facts(e: CompanionEvent): Record<string, string> {
  switch (e.type) {
    case 'reminder': return { title: `“${e.title}”` };
    case 'overdue': return { count: String(e.count) };
    case 'indexed': return { count: String(e.count) };
    case 'task_saved': return { title: `“${e.title}”` };
    case 'reminder_saved': return { title: `“${e.title}”`, when: e.when };
    case 'claude_done': return { duration: e.minutes >= 60 ? `${Math.floor(e.minutes / 60)} h ${e.minutes % 60} min` : `${e.minutes} min` };
    case 'important_email': return { count: String(e.count) };
    case 'draft_reminder_cancelled': return { message: e.message };
    case 'google_done': return { text: e.text };
    case 'claude_waiting':
    case 'google_reconnect':
      return {};
  }
}

/** Fills a template; null if it misses a required fact or uses an unknown one. */
export function fill(template: string, values: Record<string, string>): string | null {
  for (const key of Object.keys(values)) if (!template.includes(`{${key}}`)) return null;
  const used = [...template.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
  if (used.some((k) => !(k in values))) return null;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => values[k]);
}

const PLAIN = (p: Personality): Personality => ({ humour: 0, sarcasm: 0, friendliness: 0, strictness: p.strictness });

/** The reaction to an app event, in the companion's voice. Facts always come from the event. */
export function reactAs(c: Voice, event: CompanionEvent, p: Personality): Reaction {
  const shared = react(event, p);
  if (!shared.line) return shared;
  const own = c.eventLines[eventKey(event)];
  const filled = own ? fill(own, facts(event)) : null;
  if (filled) return { ...shared, line: { ...shared.line, text: filled } };
  if (fitsVoice(c, shared.line.text)) return shared;
  const plain = react(event, PLAIN(p)).line;
  if (plain && fitsVoice(c, plain.text)) return { ...shared, line: { ...shared.line, text: plain.text } };
  return { ...shared, line: null };
}

/**
 * A panel line in the companion's voice. `pick` chooses among the manifest's lines for "hello"
 * (random in the app, fixed in tests).
 */
export function panelLine(c: Voice, event: string, line: BubbleLine | null, pick: (n: number) => number = (n) => Math.floor(Math.random() * n)): BubbleLine | null {
  if (!line) return null;
  const own = c.eventLines[`panel_${event}`];
  // The tasks line carries a count, which a fixed line would drop, so it always uses the shared line.
  if (own && !own.includes('{') && event !== 'tasks') return { ...line, text: own };
  if (event === 'hello' && c.id !== 'smoi' && c.lines.length > 0) return { ...line, text: c.lines[pick(c.lines.length)] };
  return fitsVoice(c, line.text) ? line : null;
}
